"""SYNTHETIC demo data: a seeded generator of realistic Indian personal-finance statements.

Nothing here is real data. The generator writes two CSV files in the shapes real
exports come in, then the demo loads them through the *normal* ETL pipeline, so
the demo exercises the same code a real import does:

* ``savings_account.csv``: day-first dates (``DD/MM/YYYY``), split
  ``Withdrawal Amt.`` / ``Deposit Amt.`` columns, Indian digit grouping, a
  two-line preamble before the header, UTF-8 with BOM (as Excel saves it).
* ``credit_card.csv``: ISO dates, one signed ``Amount`` column with a ``₹``
  prefix where purchases are positive and payments negative (``debit_positive``).

The same ``seed`` and ``end_month`` always produce byte-identical files.
"""

from __future__ import annotations

import csv
import random
import sqlite3
from calendar import monthrange
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from expense_dashboard import queries as q
from expense_dashboard.etl import ColumnMapping, ImportResult, import_csv
from expense_dashboard.money import group_indian

SYNTHETIC_BANNER = "SYNTHETIC DEMO DATA - generated by `expense demo`, not a real statement"

BANK_MAPPING = ColumnMapping(
    date="Date",
    description="Narration",
    debit="Withdrawal Amt.",
    credit="Deposit Amt.",
    date_format="%d/%m/%Y",
    skip_rows=2,
)
CARD_MAPPING = ColumnMapping(
    date="Transaction Date",
    description="Description",
    amount="Amount",
    amount_sign="debit_positive",
)

#: Monthly budgets (rupees) applied to every demo month.
DEMO_BUDGETS: dict[str, int] = {
    "Rent": 24_000,
    "Groceries": 9_000,
    "Food Delivery": 4_500,
    "Dining Out": 4_000,
    "Fuel": 7_000,
    "Transport": 3_000,
    "Utilities": 2_500,
    "Mobile & Internet": 1_500,
    "Subscriptions": 1_000,
    "Shopping": 6_000,
    "Health": 1_500,
    "Entertainment": 1_500,
}

_FRIENDS = ["RAHUL SHARMA", "PRIYA NAIR", "ANKIT GUPTA", "SNEHA IYER", "VIKRAM SINGH", "NEHA JOSHI"]


@dataclass(frozen=True)
class Txn:
    day: date
    narration: str
    paise: int  # > 0
    is_debit: bool
    on_card: bool = False


class _Gen:
    def __init__(self, seed: int):
        self.r = random.Random(seed)

    def ref(self) -> str:
        return str(self.r.randrange(10**11, 10**12))

    def rupees(self, lo: float, hi: float, *, mode: float | None = None, step: int = 1) -> int:
        """Triangular-distributed rupee amount in paise, rounded to ``step`` rupees."""
        value = self.r.triangular(lo, hi, mode if mode is not None else (lo + hi) / 3)
        return max(step, round(value / step) * step) * 100

    def day(self, year: int, month: int, lo: int = 1, hi: int | None = None) -> date:
        last = monthrange(year, month)[1]
        hi = min(hi or last, last)
        return date(year, month, self.r.randint(min(lo, hi), hi))

    def weekend_biased_day(self, year: int, month: int) -> date:
        """Food delivery happens more on Fri-Sun: resample weekdays 50% of the time."""
        d = self.day(year, month)
        if d.weekday() < 4 and self.r.random() < 0.5:
            d = self.day(year, month)
        return d


def generate_transactions(seed: int, end_month: str, months: int = 12) -> list[Txn]:
    """Return ``months`` months of synthetic transactions ending at ``end_month``."""
    g = _Gen(seed)
    out: list[Txn] = []
    first = q.add_months(end_month, -(months - 1))
    card_spend: dict[str, int] = {}
    end_year, end_mon = map(int, end_month.split("-"))
    appraisal = f"{end_year if end_mon >= 4 else end_year - 1}-04"  # latest April in range

    for month in q.month_range(first, end_month):
        y, m = map(int, month.split("-"))
        festive = m in (10, 11)  # Dussehra / Diwali shopping season
        summer = m in (4, 5, 6)

        def add(
            d: date, text: str, paise: int, debit: bool = True, card: bool = False, _m=month
        ) -> None:
            out.append(Txn(d, text, paise, debit, card))
            if card and debit:
                card_spend[_m] = card_spend.get(_m, 0) + paise

        # Income and fixed outgoings ------------------------------------------------
        salary = 99_900 if month >= appraisal else 92_500  # April appraisal
        add(
            date(y, m, 1),
            f"NEFT/ACME TECHNOLOGIES PVT LTD/SALARY {date(y, m, 1):%b %Y}".upper(),
            salary * 100,
            debit=False,
        )
        add(g.day(y, m, 2, 4), f"UPI/RAMESH KUMAR/{g.ref()}/HOUSE RENT", 24_000 * 100)
        add(date(y, m, 5), "NACH/ZERODHA BROKING LTD/SIP", 5_000 * 100)
        electricity = g.rupees(900, 1_400, mode=1_050) * (1.8 if summer else 1.0)
        add(g.day(y, m, 8, 12), f"BBPS/BESCOM ELECTRICITY BILL/{g.ref()}", int(electricity))
        add(g.day(y, m, 9, 11), f"UPI/ACT FIBERNET/{g.ref()}", 1_059 * 100)
        add(g.day(y, m, 14, 16), f"UPI/JIO PREPAID RECHARGE/{g.ref()}", 349 * 100)
        add(g.day(y, m, 7, 7), "NETFLIX.COM MUMBAI", 649 * 100, card=True)
        add(g.day(y, m, 12, 12), "SPOTIFY INDIA", 119 * 100, card=True)
        if m == 3:
            add(g.day(y, m, 20, 22), "AMAZON PRIME MEMBERSHIP", 1_499 * 100, card=True)
        add(g.day(y, m, 1, 3), f"UPI/BMRCL METRO CARD RECHARGE/{g.ref()}", 500 * 100)

        # Groceries ---------------------------------------------------------------
        for _ in range(g.r.randint(6, 9)):
            shop = g.r.choice(
                [
                    "UPI/BLINKIT/",
                    "UPI/ZEPTO MARKETPLACE/",
                    "UPI/BIGBASKET/",
                    "UPI/SWIGGY INSTAMART/",
                    "POS/DMART AVENUE SUPERMARTS/",
                ]
            )
            add(g.day(y, m), f"{shop}{g.ref()}", g.rupees(180, 2_600, mode=650))
        for _ in range(g.r.randint(2, 4)):
            add(g.day(y, m), f"UPI/SHARMA KIRANA STORE/{g.ref()}", g.rupees(60, 700, mode=180))

        # Food -------------------------------------------------------------------
        for _ in range(g.r.randint(8, 14) + (3 if festive else 0)):
            app = g.r.choice(["UPI/SWIGGY/", "UPI/ZOMATO LTD/"])
            add(g.weekend_biased_day(y, m), f"{app}{g.ref()}", g.rupees(160, 900, mode=320))
        for _ in range(g.r.randint(2, 4)):
            place = g.r.choice(
                [
                    "CHAAYOS CAFE",
                    "STARBUCKS COFFEE",
                    "BARBEQUE NATION",
                    "HALDIRAM RESTAURANT",
                    "THIRD WAVE COFFEE ROASTERS",
                    "TOIT BREWPUB",
                ]
            )
            add(g.day(y, m), place, g.rupees(250, 3_200, mode=700), card=True)
        for _ in range(g.r.randint(6, 14)):  # small cash-like UPI payments, mostly unrules-able
            add(g.day(y, m), f"UPI/RAJU TEA STALL/{g.ref()}", g.rupees(20, 120, mode=30, step=10))

        # Getting around -----------------------------------------------------------
        for _ in range(g.r.randint(3, 4)):
            pump = g.r.choice(["HPCL", "IOCL", "BPCL"])
            add(
                g.day(y, m),
                f"POS/{pump} FUEL STATION/{g.ref()}",
                g.rupees(1_400, 2_600, mode=2_000, step=100),
            )
        for _ in range(g.r.randint(4, 10)):
            ride = g.r.choice(["UPI/UBER INDIA/", "UPI/OLA CABS/", "UPI/RAPIDO/"])
            add(g.day(y, m), f"{ride}{g.ref()}", g.rupees(70, 650, mode=180))

        # Discretionary ------------------------------------------------------------
        for _ in range(g.r.randint(1, 4) + (g.r.randint(2, 4) if festive else 0)):
            store = g.r.choice(["AMAZON PAY INDIA", "FLIPKART INTERNET", "MYNTRA DESIGNS"])
            hi = 8_000 if festive else 4_500
            add(g.day(y, m), store, g.rupees(300, hi, mode=900), card=True)
        for _ in range(g.r.randint(0, 2)):
            add(g.day(y, m), f"UPI/APOLLO PHARMACY/{g.ref()}", g.rupees(120, 1_800, mode=350))
        for _ in range(g.r.randint(0, 2)):
            venue = g.r.choice(["BOOKMYSHOW", "PVR INOX LTD"])
            add(g.day(y, m), venue, g.rupees(250, 1_400, mode=600), card=True)
        if g.r.random() < 0.6:
            add(
                g.day(y, m),
                "URBAN COMPANY SALON AT HOME",
                g.rupees(499, 1_599, mode=799, step=50),
                card=True,
            )
        if m in (5, 12) or g.r.random() < 0.15:
            add(
                g.day(y, m),
                f"IRCTC E-TICKET/{g.ref()}",
                g.rupees(600, 3_200, mode=1_200),
                card=True,
            )
            if m in (5, 12):
                add(
                    g.day(y, m), "INDIGO AIRLINES 6E", g.rupees(4_200, 9_500, mode=5_500), card=True
                )
        if g.r.random() < 0.55:
            add(
                g.day(y, m),
                f"ATM CASH WDL/MG ROAD/{g.ref()}",
                g.r.choice([2_000, 3_000, 5_000]) * 100,
            )

        # People -------------------------------------------------------------------
        for _ in range(g.r.randint(2, 6)):
            friend = g.r.choice(_FRIENDS)
            add(g.day(y, m), f"UPI/{friend}/{g.ref()}/PAID VIA APP", g.rupees(80, 1_500, mode=300))
        if g.r.random() < 0.5:
            friend = g.r.choice(_FRIENDS)
            add(
                g.day(y, m),
                f"UPI/{friend}/{g.ref()}/RECEIVED",
                g.rupees(200, 2_500, mode=600),
                debit=False,
            )
        if g.r.random() < 0.3:
            add(g.day(y, m), f"UPI/SWIGGY/{g.ref()}/REFUND", g.rupees(120, 450), debit=False)
        if m in (3, 6, 9, 12):
            add(
                date(y, m, monthrange(y, m)[1]),
                "INTEREST CREDIT SB ACCOUNT",
                g.rupees(600, 1_400),
                debit=False,
            )

    # Each month's card bill is paid on the 18th of the following month, from the bank
    # account (a transfer) and shows up on the card as a payment received.
    for month, total in sorted(card_spend.items()):
        pay_month = q.add_months(month, 1)
        if pay_month > end_month:
            continue
        py, pm = map(int, pay_month.split("-"))
        due = date(py, pm, 18)
        out.append(Txn(due, f"BILLDESK/CREDIT CARD PAYMENT/{g.ref()}", total, True))
        out.append(Txn(due, "PAYMENT RECEIVED - THANK YOU", total, False, on_card=True))

    out.sort(key=lambda t: (t.day, t.on_card, t.narration))
    return out


def _fmt(paise: int) -> str:
    rupees, rem = divmod(paise, 100)
    return f"{group_indian(rupees)}.{rem:02d}"


def write_statements(txns: list[Txn], out_dir: str | Path) -> tuple[Path, Path]:
    """Write the savings-account and credit-card CSVs; return their paths."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    bank_path, card_path = out / "savings_account.csv", out / "credit_card.csv"

    balance = 1_50_000 * 100
    with bank_path.open("w", newline="", encoding="utf-8-sig") as fh:
        fh.write(f"{SYNTHETIC_BANNER}\n")
        fh.write("Account: XXXXXXXX4821 (fictional)  Currency: INR\n")
        writer = csv.writer(fh)
        writer.writerow(
            [
                "Date",
                "Narration",
                "Chq./Ref.No.",
                "Withdrawal Amt.",
                "Deposit Amt.",
                "Closing Balance",
            ]
        )
        for i, t in enumerate(x for x in txns if not x.on_card):
            balance += -t.paise if t.is_debit else t.paise
            writer.writerow(
                [
                    t.day.strftime("%d/%m/%Y"),
                    t.narration,
                    f"{i + 1:010d}",
                    _fmt(t.paise) if t.is_debit else "",
                    "" if t.is_debit else _fmt(t.paise),
                    _fmt(balance),
                ]
            )

    with card_path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["Transaction Date", "Description", "Amount"])
        for t in (x for x in txns if x.on_card):
            sign = "" if t.is_debit else "-"
            writer.writerow([t.day.isoformat(), t.narration, f"{sign}₹{_fmt(t.paise)}"])
    return bank_path, card_path


def load_demo(
    conn: sqlite3.Connection,
    out_dir: str | Path,
    *,
    seed: int = 42,
    end_month: str,
    months: int = 12,
) -> list[ImportResult]:
    """Generate, write and import the synthetic statements, then set demo budgets."""
    txns = generate_transactions(seed, end_month, months)
    bank_path, card_path = write_statements(txns, out_dir)
    results = [
        import_csv(conn, bank_path, BANK_MAPPING, strict=True),
        import_csv(conn, card_path, CARD_MAPPING, strict=True),
    ]
    budget_months = q.month_range(q.add_months(end_month, -(months - 1)), end_month)
    for category, rupees in DEMO_BUDGETS.items():
        q.set_budget(conn, category, rupees * 100, budget_months)
    return results
